--comment: Initial schema for movies, people (actors and directors) and genres.

-- Actors and directors. A person is identified by first + last name (case-insensitive).
CREATE TABLE person (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(100) NOT NULL,
    last_name  VARCHAR(100) NOT NULL
);
CREATE UNIQUE INDEX uq_person_name ON person (lower(first_name), lower(last_name));

-- Genre names are unique case-insensitively ("Sci-fi" and "sci-fi" are the same genre).
CREATE TABLE genre (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL
);
CREATE UNIQUE INDEX uq_genre_name ON genre (lower(name));

-- A movie is identified by name (case-insensitive) + release year.
CREATE TABLE movie (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(255)  NOT NULL,
    release_year INTEGER       NOT NULL,
    age_limit    INTEGER       NOT NULL,
    rating       INTEGER       NOT NULL,
    synopsis     VARCHAR(2000),
    director_id  BIGINT        NOT NULL,
    CONSTRAINT fk_movie_director FOREIGN KEY (director_id) REFERENCES person (id),
    CONSTRAINT ck_movie_release_year CHECK (release_year BETWEEN 1888 AND 2100),
    CONSTRAINT ck_movie_age_limit CHECK (age_limit BETWEEN 0 AND 21),
    CONSTRAINT ck_movie_rating CHECK (rating BETWEEN 1 AND 5)
);
CREATE UNIQUE INDEX uq_movie_name_year ON movie (lower(name), release_year);
CREATE INDEX ix_movie_director ON movie (director_id);

-- Actors of a movie. "position" keeps the billing order (lead actor first).
CREATE TABLE movie_actor (
    movie_id  BIGINT  NOT NULL,
    position  INTEGER NOT NULL,
    person_id BIGINT  NOT NULL,
    CONSTRAINT pk_movie_actor PRIMARY KEY (movie_id, position),
    CONSTRAINT uq_movie_actor_person UNIQUE (movie_id, person_id),
    CONSTRAINT fk_movie_actor_movie FOREIGN KEY (movie_id) REFERENCES movie (id) ON DELETE CASCADE,
    CONSTRAINT fk_movie_actor_person FOREIGN KEY (person_id) REFERENCES person (id)
);
CREATE INDEX ix_movie_actor_person ON movie_actor (person_id);

CREATE TABLE movie_genre (
    movie_id BIGINT NOT NULL,
    genre_id BIGINT NOT NULL,
    CONSTRAINT pk_movie_genre PRIMARY KEY (movie_id, genre_id),
    CONSTRAINT fk_movie_genre_movie FOREIGN KEY (movie_id) REFERENCES movie (id) ON DELETE CASCADE,
    CONSTRAINT fk_movie_genre_genre FOREIGN KEY (genre_id) REFERENCES genre (id)
);
CREATE INDEX ix_movie_genre_genre ON movie_genre (genre_id);

--rollback DROP TABLE movie_genre, movie_actor, movie, genre, person;
