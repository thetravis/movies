package com.example.movies.service.mapper;

import com.example.movies.domain.Person;
import com.example.movies.generated.model.PersonDto;
import com.example.movies.repository.PersonRepository;
import jakarta.validation.Validator;
import org.mapstruct.BeanMapping;
import org.mapstruct.Mapper;
import org.mapstruct.MappingConstants;
import org.mapstruct.Named;
import org.mapstruct.ReportingPolicy;
import org.springframework.beans.factory.annotation.Autowired;

/**
 * Maps persons (actors and directors) between the API and the database.
 * <p>
 * {@link #toEntity} reuses an existing person with the same name (case-insensitive) or saves a new
 * one, so it reads and writes the database: call it only inside a transaction
 * ({@code MovieService}), so that a rejected movie also rolls back the persons created for it.
 * <p>
 * Field-by-field copying is generated by MapStruct; unmapped fields in either direction fail the
 * build.
 */
@Mapper(componentModel = MappingConstants.ComponentModel.SPRING, uses = TextMapper.class,
        unmappedSourcePolicy = ReportingPolicy.ERROR, unmappedTargetPolicy = ReportingPolicy.ERROR)
public abstract class PersonMapper {

    // Field injection: MapStruct generates the subclass and its constructor.
    @Autowired
    private PersonRepository personRepository;

    @Autowired
    private Validator validator;

    /** The API identifies persons by name only, so the database id is not exposed. */
    @BeanMapping(ignoreUnmappedSourceProperties = "id")
    public abstract PersonDto toDto(Person person);

    /**
     * Returns the existing person with this name, or saves and returns a new one. Names are trimmed.
     * An invalid person (e.g. blank name) is returned unsaved, so that validating the movie reports
     * the error with the full path (e.g. {@code director.firstName}).
     */
    public Person toEntity(PersonDto dto) {
        if (dto == null) {
            return null;
        }
        Person person = newPerson(dto);
        if (!validator.validate(person).isEmpty()) {
            return person;
        }
        return personRepository
                .findByFirstNameIgnoreCaseAndLastNameIgnoreCase(person.getFirstName(), person.getLastName())
                .orElseGet(() -> personRepository.save(person));
    }

    /** Generated copy of all fields (trimmed). {@code @Named}: used only by {@link #toEntity}. */
    @Named("newPerson")
    protected abstract Person newPerson(PersonDto dto);
}
